	local b64_chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
	
	local function decode_b64(data)
		data = string.gsub(data, '[^'..b64_chars..'=]', '')
		local bits = ''
		for i = 1, #data do
			local x = string.sub(data, i, i)
			if x ~= '=' then
				local f = b64_chars:find(x, 1, true) - 1
				local r = ''
				for j = 6, 1, -1 do
					r = r .. (f % 2^j - f % 2^(j-1) > 0 and '1' or '0')
				end
				bits = bits .. r
			end
		end
		local len = #bits - (#bits % 8)
		bits = string.sub(bits, 1, len)
		return (bits:gsub('%d%d%d%d%d%d%d%d', function(x)
			local c = 0
			for i = 1, 8 do
				c = c + (x:sub(i,i) == '1' and 2^(8-i) or 0)
			end
			return string.char(c)
		end))
	end

